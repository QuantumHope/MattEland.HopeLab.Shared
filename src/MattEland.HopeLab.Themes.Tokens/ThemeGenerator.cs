using System.Text;
using System.Text.Json.Nodes;

namespace MattEland.HopeLab.Themes.Tokens;

/// <summary>Every file the token set generates, by path from the repository root, with its content.</summary>
public sealed record GeneratedFiles(IReadOnlyDictionary<string, string> Files, IReadOnlyList<string> Warnings);

/// <summary>
/// Turns the token set into the files apps use: one CSS block per theme (plus a base block and an index) under
/// <c>tokens/css/</c>, and one Avalonia resource dictionary per theme plus the catalogue in the Themes package.
/// </summary>
public static class ThemeGenerator
{
    public const string CssFolder = "tokens/css";
    public const string AvaloniaProject = "src/MattEland.HopeLab.Themes";
    public const string AvaloniaAssembly = "MattEland.HopeLab.Themes";
    public const string DictionaryNamespace = AvaloniaAssembly + ".Dictionaries";

    /// <summary>The theme the CSS writes onto <c>:root</c> and the catalogue names as the default.</summary>
    public static string DefaultTheme(string tokensFolder) =>
        JsonNode.Parse(File.ReadAllText(Path.Combine(tokensFolder, "themes.json")))?["default"]?.GetValue<string>()
        ?? throw new FormatException("themes.json has no default.");

    public static GeneratedFiles Generate(TokenSet set, string defaultTheme)
    {
        var files = new SortedDictionary<string, string>(StringComparer.Ordinal);
        var warnings = new List<string>();

        var css = new CssWriter(set.Contract);
        files[$"{CssFolder}/base.css"] = css.WriteBase();
        foreach (var t in set.Themes) files[$"{CssFolder}/{t.Id}.css"] = css.WriteTheme(t, t.Id == defaultTheme);
        files[$"{CssFolder}/index.css"] = CssWriter.WriteIndex(set);

        var axaml = new AxamlWriter(set.Contract, $"avares://{AvaloniaAssembly}/Assets/Fonts", DictionaryNamespace);
        foreach (var t in set.Themes)
            files[$"{AvaloniaProject}/Themes/{FileName(t)}"] = axaml.Write(set.Resolve(t));
        warnings.AddRange(axaml.Warnings);
        files[$"{AvaloniaProject}/ThemeCatalog.g.cs"] = Catalog(set, defaultTheme);
        files[$"{AvaloniaProject}/Themes/Dictionaries.g.cs"] = Dictionaries(set);

        return new GeneratedFiles(files, warnings);
    }

    /// <summary><c>hc-dark</c> → <c>HcDark.axaml</c>.</summary>
    public static string FileName(ThemeSource t) => TokenNames.Pascal(t.Id) + ".axaml";

    private static string Catalog(TokenSet set, string defaultTheme)
    {
        static string Cs(string? s) => s is null ? "null" : "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
        var x = new StringBuilder();
        x.AppendLine("// <auto-generated>");
        x.AppendLine("// Written by tools/ThemeTokens from tokens/themes.json and tokens/themes/*.json. Edit those and regenerate.");
        x.AppendLine("// </auto-generated>");
        x.AppendLine($"namespace {AvaloniaAssembly};");
        x.AppendLine();
        x.AppendLine("public static partial class ThemeCatalog");
        x.AppendLine("{");
        x.AppendLine($"    /// <summary>The theme an app starts on when the user hasn't picked one.</summary>");
        x.AppendLine($"    public const string DefaultId = {Cs(defaultTheme)};");
        x.AppendLine();
        x.AppendLine("    /// <summary>Every shared theme, in catalogue order.</summary>");
        x.AppendLine("    public static IReadOnlyList<ThemeInfo> All { get; } =");
        x.AppendLine("    [");
        foreach (var t in set.Themes)
        {
            x.AppendLine($"        new({Cs(t.Id)}, {Cs(t.Name)}, {Cs(t.Description)}, {Cs(FileName(t))},");
            x.AppendLine($"            IsLight: {(t.IsLight ? "true" : "false")}, HighContrast: {(t.HighContrast ? "true" : "false")}, " +
                         $"Icon: {Cs(t.Icon)}, Motto: {Cs(t.Motto)},");
            x.AppendLine($"            Create: static () => new Dictionaries.{TokenNames.Pascal(t.Id)}()),");
        }
        x.AppendLine("    ];");
        x.AppendLine("}");
        return x.ToString();
    }

    /// <summary>
    /// A class for each theme's dictionary, so an app creates one with <c>new</c>, which compiled XAML makes safe to trim
    /// and to compile ahead of time (loading by URI is not).
    /// </summary>
    private static string Dictionaries(TokenSet set)
    {
        var x = new StringBuilder();
        x.AppendLine("// <auto-generated>");
        x.AppendLine("// Written by tools/ThemeTokens: one class per generated theme dictionary (its x:Class). Regenerate instead of editing.");
        x.AppendLine("// </auto-generated>");
        x.AppendLine("using Avalonia.Controls;");
        x.AppendLine("using Avalonia.Markup.Xaml;");
        x.AppendLine();
        x.AppendLine($"namespace {DictionaryNamespace};");
        foreach (var t in set.Themes)
        {
            x.AppendLine();
            x.AppendLine($"/// <summary>The {t.Name.Replace("&", "&amp;").Replace("<", "&lt;")} theme's resources.</summary>");
            x.AppendLine($"public partial class {TokenNames.Pascal(t.Id)} : ResourceDictionary");
            x.AppendLine("{");
            x.AppendLine($"    public {TokenNames.Pascal(t.Id)}() => AvaloniaXamlLoader.Load(this);");
            x.AppendLine("}");
        }
        return x.ToString();
    }

    /// <summary>The repository root: the nearest folder above <paramref name="start"/> holding the solution.</summary>
    public static string? FindRepoRoot(string start)
    {
        for (var d = new DirectoryInfo(start); d is not null; d = d.Parent)
            if (File.Exists(Path.Combine(d.FullName, "MattEland.HopeLab.Shared.slnx"))) return d.FullName;
        return null;
    }
}
