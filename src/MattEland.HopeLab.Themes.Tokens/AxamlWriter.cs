using System.Globalization;
using System.Security;
using System.Text;
using System.Text.RegularExpressions;

namespace MattEland.HopeLab.Themes.Tokens;

/// <summary>
/// Writes one theme as an Avalonia resource dictionary. Every key starts with <c>Lab.</c>:
/// <list type="bullet">
/// <item>each contract colour as <c>Lab.X.Color</c> (a <c>Color</c>) and <c>Lab.X</c> (a brush);</item>
/// <item>gradients as <c>LinearGradientBrush</c>, glows as <c>BoxShadows</c>, fonts as <c>FontFamily</c>;</item>
/// <item>the type scale, spacing, radii and the assistant's line style as numbers;</item>
/// <item>a few derived brushes every app wanted (washes, a scrim, a hover step on the primary accent, chart slots 5 to 7);</item>
/// <item>the theme's own chrome colours as <c>Lab.Chrome.*</c>.</item>
/// </list>
/// Anything that can't be expressed in Avalonia (a radial gradient, <c>color-mix()</c>, <c>currentColor</c>) is left out
/// and listed in <see cref="Warnings"/>.
/// </summary>
public sealed partial class AxamlWriter(TokenContract contract, string fontBase, string classNamespace)
{
    /// <summary>The faces the Avalonia package bundles; any other face in a stack falls through to the next.</summary>
    public static IReadOnlySet<string> BundledFaces { get; } = new HashSet<string>(StringComparer.Ordinal)
    {
        "Inter", "JetBrains Mono", "Share Tech Mono", "Cinzel", "Barlow", "IBM Plex Mono", "Oxanium", "Rajdhani", "Nunito",
        "Exo 2", "Saira Condensed", "Atkinson Hyperlegible", "VT323", "Orbitron", "Antonio", "Quicksand", "Michroma",
        "Lora", "Audiowide", "Poppins", "Mulish", "League Spartan", "UnifrakturMaguntia",
    };

    private static readonly string[] DarkSeries = ["#3987E5", "#D95926", "#199E70", "#C98500", "#D55181", "#008300", "#9085E9"];
    private static readonly string[] LightSeries = ["#2A78D6", "#C2531F", "#148A5E", "#9C6B00", "#C23F72", "#007A00", "#6B5BD6"];

    private readonly StringBuilder _x = new();
    private ResolvedTheme _t = null!;

    public List<string> Warnings { get; } = [];

    public string Write(ResolvedTheme theme)
    {
        _x.Clear();
        _t = theme;
        var s = theme.Theme;
        var dark = !s.IsLight;

        Line("<!--");
        Line($"  {Comment(s.Name)}{(s.Description.Length > 0 ? ": " + Comment(s.Description) : "")}.");
        Line($"  GENERATED by tools/ThemeTokens from tokens/themes/{s.Id}.json. Edit the token file and regenerate.");
        Line("-->");
        Line("<ResourceDictionary xmlns=\"https://github.com/avaloniaui\"");
        Line("                    xmlns:x=\"http://schemas.microsoft.com/winfx/2006/xaml\"");
        Line($"                    x:Class=\"{classNamespace}.{TokenNames.Pascal(s.Id)}\">");

        string? group = null;
        foreach (var t in contract.Tokens)
        {
            var g = t.Name[..t.Name.IndexOf('.')];
            if (g != group && t.Kind is TokenKind.Color or TokenKind.Gradient or TokenKind.Shadow or TokenKind.Font)
            {
                Line();
                Line($"  <!-- {g} -->");
                group = g;
            }
            switch (t.Kind)
            {
                case TokenKind.Color: ColorPair(t); break;
                case TokenKind.Gradient: Gradient(t.ResourceKey, t.Css, theme.Value(t.Name)); break;
                case TokenKind.Shadow: Shadow(t); break;
                case TokenKind.Font: FontFamily(t); break;
            }
        }

        var text = Must("text.primary");
        var panel = Must("surface.panel");
        var canvas = Must("surface.canvas");
        var primary = Must("accent.primary");

        Line();
        Line("  <!-- Derived: the primary accent under the pointer, washes behind badges and banners, the dialog scrim -->");
        Brush("Lab.Accent.Primary.Hot", dark ? primary.Mix(TokenColor.White, 0.3) : primary.Mix(TokenColor.Black, 0.2));
        Brush("Lab.Wash.Primary", primary.WithAlpha(0x29));
        Brush("Lab.Wash.Error", Must("accent.error").WithAlpha(0x29));
        Brush("Lab.Wash.Link", Must("accent.link").WithAlpha(0x29));
        Brush("Lab.Wash.Warning", Must("accent.warning").WithAlpha(0x29));
        Brush("Lab.Wash.Hover", text.WithAlpha(dark ? (byte)0x0D : (byte)0x0A));
        Brush("Lab.Wash.Selected", primary.WithAlpha(0x1F));
        Brush("Lab.Scrim", dark ? canvas.WithAlpha(0xB3) : text.WithAlpha(0x66));

        Line("  <!-- Derived: chart slots 5 to 7 and Other, which the tokens don't cover, at 3:1 on the panel -->");
        var steps = dark ? DarkSeries : LightSeries;
        for (var slot = 5; slot <= 7; slot++) Brush($"Lab.Viz.Series{slot}", TokenColor.Parse(steps[slot - 1])!.Value.AtLeast(3, panel));
        Brush("Lab.Viz.Other", TokenColor.Parse("#6E6C80")!.Value.AtLeast(3, panel));

        Line("  <!-- Derived: Fluent's palette, for apps that build FluentTheme from the theme -->");
        Color("Lab.Fluent.Accent", primary.WithAlpha(255));
        Color("Lab.Fluent.Region", canvas);
        Color("Lab.Fluent.BaseHigh", text);
        Color("Lab.Fluent.ChromeMedium", Must("surface.elevated"));
        Color("Lab.Fluent.ChromeMediumLow", panel);
        Color("Lab.Fluent.ChromeLow", Must("surface.header"));
        Color("Lab.Fluent.ErrorText", Must("accent.error"));

        Line();
        Line("  <!-- Type scale (size, weight, and line height in pixels), spacing and radii -->");
        foreach (var role in contract.Tokens.Where(t => t.Name.StartsWith("type.", StringComparison.Ordinal) && t.Name.EndsWith(".size", StringComparison.Ordinal)))
        {
            var r = role.Name[5..^5];
            var key = "Lab.Type." + TokenNames.Pascal(r);
            var size = Number($"type.{r}.size");
            Dbl(key + ".Size", size);
            Line($"  <FontWeight x:Key=\"{key}.Weight\">{Weight(Number($"type.{r}.weight"))}</FontWeight>");
            Dbl(key + ".LineHeight", Math.Round(size * Number($"type.{r}.line-height"), 2));
        }
        foreach (var t in contract.Tokens.Where(t => t.Name.StartsWith("space.", StringComparison.Ordinal)))
            Dbl(t.ResourceKey, Number(t.Name));
        Line($"  <CornerRadius x:Key=\"Lab.Radius\">{(s.HighContrast ? 2 : 6)}</CornerRadius>");
        Line($"  <CornerRadius x:Key=\"Lab.Radius.Pill\">{(s.HighContrast ? 2 : 10)}</CornerRadius>");

        Line();
        Line("  <!-- The assistant's line style, and which signature detail the theme's chrome draws -->");
        foreach (var n in new[] { "line", "plate", "seam", "glow" }) Dbl($"Lab.Persona.{TokenNames.Pascal(n)}", Number($"persona.{n}"));
        Str("Lab.Persona.Chrome", theme.Value("persona.chrome") ?? "none");

        Line("  <!-- The theme itself -->");
        Str("Lab.Theme.Id", s.Id);
        Str("Lab.Theme.Name", s.Name);
        if (s.Motto is { Length: > 0 } motto) Str("Lab.Theme.Motto", motto);
        else Line("  <x:String x:Key=\"Lab.Theme.Motto\">&#160;</x:String>"); // an x:String can't be empty

        if (s.Chrome.Count > 0)
        {
            Line();
            Line("  <!-- Chrome: this theme's own decoration colours (decoration only; never text or meaning) -->");
            foreach (var (k, _) in s.Chrome)
            {
                var key = "Lab.Chrome." + TokenNames.Pascal(k);
                var v = theme.Value("chrome." + k);
                if (TokenColor.Parse(v) is { } c) Brush(key, c);
                else if (v?.StartsWith("linear-gradient", StringComparison.Ordinal) == true) Gradient(key, $"{s.ChromePrefix}-{k}", v);
                else if (v is null || !ShadowLine(key, v)) Warn($"chrome {k} '{v}' is not a colour, a linear gradient or a shadow; left out");
            }
        }

        Line("</ResourceDictionary>");
        return _x.ToString();
    }

    private TokenColor Must(string name) =>
        _t.Color(name) ?? throw new InvalidOperationException($"{_t.Theme.Id}: {name} is '{_t.Value(name)}', not a colour.");

    private double Number(string name) =>
        double.Parse(_t.Value(name) ?? throw new InvalidOperationException($"{_t.Theme.Id}: {name} has no value."), CultureInfo.InvariantCulture);

    private void Warn(string message) => Warnings.Add($"{_t.Theme.Id}: {message}");

    private void ColorPair(TokenDefinition t)
    {
        var v = _t.Value(t.Name);
        if (TokenColor.Parse(v) is not { } c)
        {
            if (v is not null) Warn($"{t.Name} '{v}' is not a plain colour; left out");
            return;
        }
        if (t.Name.StartsWith("viz.series-", StringComparison.Ordinal) && _t.Color("surface.panel") is { } panel && c.Contrast(panel) < 3)
        {
            // A chart mark has to reach 3:1 (WCAG 1.4.11) on the panel it sits on. Where the token doesn't, Avalonia gets
            // the stock step for that slot, lifted until it does; the CSS keeps the token. Fix the token to remove this.
            var slot = int.Parse(t.Name["viz.series-".Length..], CultureInfo.InvariantCulture);
            Warn($"{t.Name} is {c.Contrast(panel):0.00}:1 on the panel; Avalonia uses the stock step for slot {slot}");
            c = TokenColor.Parse((_t.Theme.IsLight ? LightSeries : DarkSeries)[slot - 1])!.Value.AtLeast(3, panel);
        }
        Color(t.ResourceKey + ".Color", c);
        Line($"  <SolidColorBrush x:Key=\"{t.ResourceKey}\" Color=\"{{StaticResource {t.ResourceKey}.Color}}\" />");
    }

    private void Shadow(TokenDefinition t)
    {
        if (_t.Value(t.Name) is { } v && !ShadowLine(t.ResourceKey, v)) Warn($"{t.Name} '{v}' isn't offsets and a colour; left out");
    }

    /// <summary>A CSS box shadow (one or several) as <c>BoxShadows</c>. False when it isn't one Avalonia can draw.</summary>
    private bool ShadowLine(string key, string value)
    {
        // currentColor takes the colour of whatever it's on, which a resource can't; the app draws that glow itself
        if (value.Contains("currentColor", StringComparison.OrdinalIgnoreCase)) return true;
        var parts = new List<string>();
        foreach (var one in SplitTop(value))
        {
            var m = ShadowPattern().Match(one);
            if (!m.Success || TokenColor.Parse(m.Groups["color"].Value) is not { } color) return false;
            string N(string g) => m.Groups[g].Success ? Px(m.Groups[g].Value) : "0";
            parts.Add($"{(m.Groups["inset"].Success ? "inset " : "")}{N("x")} {N("y")} {N("blur")} {N("spread")} {color}");
        }
        Line($"  <BoxShadows x:Key=\"{key}\">{string.Join(", ", parts)}</BoxShadows>");
        return true;
    }

    [GeneratedRegex(@"^(?<inset>inset\s+)?(?<x>-?[\d.]+(?:px)?)\s+(?<y>-?[\d.]+(?:px)?)(?:\s+(?<blur>[\d.]+(?:px)?))?(?:\s+(?<spread>-?[\d.]+(?:px)?))?\s+(?<color>.+)$")]
    private static partial Regex ShadowPattern();

    private static string Px(string v) => v.EndsWith("px", StringComparison.Ordinal) ? v[..^2] : v;

    private void FontFamily(TokenDefinition t)
    {
        var stack = _t.Value(t.Name);
        if (stack is null) return;
        var fallback = t.Name == "font.mono" || stack.Contains("monospace", StringComparison.Ordinal) ? "JetBrains Mono" : "Inter";
        var names = stack.Split(',').Select(n => n.Trim().Trim('"', '\''))
            .Where(n => n.Length > 0 && n is not ("system-ui" or "-apple-system")).ToList();
        if (!names.Contains(fallback))
        {
            // The bundled face goes just before the generic family, to catch anything the theme's faces don't have
            var generic = names.FindIndex(n => n is "sans-serif" or "monospace" or "serif");
            names.Insert(generic >= 0 ? generic : names.Count, fallback);
        }
        var parts = names.Select(n => BundledFaces.Contains(n) ? $"{fontBase}#{n}" : n);
        Line($"  <FontFamily x:Key=\"{t.ResourceKey}\">{SecurityElement.Escape(string.Join(", ", parts))}</FontFamily>");
    }

    /// <summary>A CSS <c>linear-gradient()</c> as a brush; anything else is left out with a warning.</summary>
    private void Gradient(string key, string cssName, string? raw)
    {
        if (raw is null) return;
        if (TokenColor.Parse(raw) is { } solid)
        {
            Brush(key, solid);
            return;
        }
        var m = Regex.Match(raw, @"^linear-gradient\((.*)\)$", RegexOptions.Singleline);
        if (!m.Success)
        {
            Warn($"--{cssName} is not a linear gradient; left out");
            return;
        }
        var args = SplitTop(m.Groups[1].Value);
        var angle = 180.0;
        if (args.Count > 0 && Regex.Match(args[0], @"^(-?[\d.]+)deg$") is { Success: true } a)
        {
            angle = double.Parse(a.Groups[1].Value, CultureInfo.InvariantCulture);
            args.RemoveAt(0);
        }
        else if (args.Count > 0 && args[0].StartsWith("to ", StringComparison.Ordinal))
        {
            angle = args[0] switch
            {
                "to top" => 0, "to top right" => 45, "to right" => 90, "to bottom right" => 135,
                "to bottom" => 180, "to bottom left" => 225, "to left" => 270, "to top left" => 315, _ => 180,
            };
            args.RemoveAt(0);
        }
        var stops = new List<(TokenColor C, double? At)>();
        foreach (var s in args)
        {
            // A colour, then no position, one, or two (a hard band: "#F25022 0 25%")
            var sm = Regex.Match(s, @"^(.*?)(?:\s+(-?[\d.]+%|0))?(?:\s+(-?[\d.]+%|0))?$");
            if (TokenColor.Parse(sm.Groups[1].Value) is not { } c)
            {
                Warn($"--{cssName} has a stop that isn't a plain colour ('{s}'); left out");
                return;
            }
            static double At(string p) => p == "0" ? 0 : double.Parse(p[..^1], CultureInfo.InvariantCulture) / 100;
            stops.Add((c, sm.Groups[2].Success ? At(sm.Groups[2].Value) : null));
            if (sm.Groups[3].Success) stops.Add((c, At(sm.Groups[3].Value)));
        }
        if (stops.Count < 2)
        {
            Warn($"--{cssName} has fewer than two stops; left out");
            return;
        }
        var rad = angle * Math.PI / 180;
        double dx = Math.Sin(rad) / 2, dy = -Math.Cos(rad) / 2;
        static string P(double x, double y) =>
            $"{(x * 100).ToString("0.#", CultureInfo.InvariantCulture)}%,{(y * 100).ToString("0.#", CultureInfo.InvariantCulture)}%";
        Line($"  <LinearGradientBrush x:Key=\"{key}\" StartPoint=\"{P(0.5 - dx, 0.5 - dy)}\" EndPoint=\"{P(0.5 + dx, 0.5 + dy)}\">");
        for (var i = 0; i < stops.Count; i++)
        {
            var at = stops[i].At ?? (double)i / (stops.Count - 1);
            Line($"    <GradientStop Offset=\"{at.ToString("0.###", CultureInfo.InvariantCulture)}\" Color=\"{stops[i].C}\" />");
        }
        Line("  </LinearGradientBrush>");
    }

    private static string Weight(double w) => w switch
    {
        <= 100 => "Thin", <= 200 => "ExtraLight", <= 300 => "Light", <= 400 => "Normal", <= 500 => "Medium",
        <= 600 => "SemiBold", <= 700 => "Bold", <= 800 => "ExtraBold", _ => "Black",
    };

    internal static List<string> SplitTop(string s)
    {
        var parts = new List<string>();
        int depth = 0, start = 0;
        for (var i = 0; i < s.Length; i++)
        {
            if (s[i] == '(') depth++;
            else if (s[i] == ')') depth--;
            else if (s[i] == ',' && depth == 0)
            {
                parts.Add(s[start..i].Trim());
                start = i + 1;
            }
        }
        parts.Add(s[start..].Trim());
        return parts;
    }

    private static string Comment(string s) => SecurityElement.Escape(s).Replace("--", "-");

    private void Line(string s = "") => _x.AppendLine(s);
    private void Color(string key, TokenColor c) => Line($"  <Color x:Key=\"{key}\">{c}</Color>");
    private void Brush(string key, TokenColor c) => Line($"  <SolidColorBrush x:Key=\"{key}\" Color=\"{c}\" />");
    private void Str(string key, string value) => Line($"  <x:String x:Key=\"{key}\">{SecurityElement.Escape(value)}</x:String>");
    private void Dbl(string key, double v) => Line($"  <x:Double x:Key=\"{key}\">{v.ToString(CultureInfo.InvariantCulture)}</x:Double>");
}
