using System.Text;
using System.Text.RegularExpressions;

namespace MattEland.HopeLab.Themes.Tokens;

/// <summary>One rule block of a stylesheet: its selector and its custom properties (and <c>color-scheme</c>).</summary>
public sealed record CssBlock(string Selector, IReadOnlyList<KeyValuePair<string, string>> Declarations)
{
    /// <summary>The theme ids the selector names as <c>[data-theme="id"]</c>.</summary>
    public IEnumerable<string> ThemeIds => CssReader.ThemeSelector().Matches(Selector).Select(m => m.Groups[1].Value);
}

/// <summary>Reads the custom properties out of a stylesheet. Comments are dropped; nested blocks are not supported.</summary>
public static partial class CssReader
{
    [GeneratedRegex(@"/\*.*?\*/", RegexOptions.Singleline)]
    private static partial Regex Comment();

    [GeneratedRegex(@"([^{}]+)\{([^{}]*)\}")]
    private static partial Regex Block();

    [GeneratedRegex(@"\[data-theme=""([\w-]+)""\]")]
    internal static partial Regex ThemeSelector();

    /// <summary>Every block that declares a custom property or <c>color-scheme</c>, in order. Property names keep no dashes.</summary>
    public static List<CssBlock> Parse(string css)
    {
        css = Comment().Replace(css, "");
        var blocks = new List<CssBlock>();
        foreach (Match b in Block().Matches(css))
        {
            var decls = new List<KeyValuePair<string, string>>();
            foreach (var raw in b.Groups[2].Value.Split(';'))
            {
                var i = raw.IndexOf(':');
                if (i < 0) continue;
                var key = raw[..i].Trim();
                var value = Normalize(raw[(i + 1)..]);
                if (key.StartsWith("--", StringComparison.Ordinal)) decls.Add(KeyValuePair.Create(key[2..], value));
                else if (key == "color-scheme") decls.Add(KeyValuePair.Create(key, value));
            }
            if (decls.Count > 0) blocks.Add(new CssBlock(b.Groups[1].Value.Trim(), decls));
        }
        return blocks;
    }

    /// <summary>A value with its whitespace collapsed, so two spellings of the same value compare equal.</summary>
    public static string Normalize(string value) => Regex.Replace(value.Trim(), @"\s+", " ");
}

/// <summary>Writes token files as CSS custom properties, one block per theme.</summary>
public sealed class CssWriter(TokenContract contract)
{
    private const string Banner = "GENERATED by tools/ThemeTokens from tokens/{0}. Edit the token file and regenerate; don't edit this file.";

    /// <summary>The properties every theme starts from (fonts, type scale, spacing): the contract's <c>base</c> defaults.</summary>
    public string WriteBase()
    {
        var x = new StringBuilder();
        x.Append("/* ").AppendFormat(Banner, "contract.json").AppendLine(" */");
        x.AppendLine(":root,").AppendLine("[data-theme] {");
        string? group = null;
        foreach (var t in contract.Tokens.Where(t => t.Base && t.Default is not null))
        {
            Group(x, t, ref group);
            Decl(x, t.Css, Value(t, t.Default!, null));
        }
        x.AppendLine("}");
        return x.ToString();
    }

    /// <summary>One theme's block. The default theme's block also applies to <c>:root</c>.</summary>
    public string WriteTheme(ThemeSource theme, bool isDefault)
    {
        var x = new StringBuilder();
        x.Append("/* ").AppendFormat(Banner, $"themes/{theme.Id}.json").AppendLine();
        x.Append("   ").Append(theme.Name);
        if (theme.Description.Length > 0) x.Append(": ").Append(theme.Description.Replace("*/", "* /"));
        x.AppendLine(" */");
        if (isDefault) x.AppendLine(":root,");
        x.Append("[data-theme=\"").Append(theme.Id).AppendLine("\"] {");
        x.Append("  color-scheme: ").Append(theme.Scheme).AppendLine(";");

        var own = theme.Tokens.ToDictionary(p => p.Key, p => p.Value, StringComparer.Ordinal);
        string? group = null;
        foreach (var t in contract.Tokens)
        {
            if (!own.TryGetValue(t.Name, out var v)) continue;
            Group(x, t, ref group);
            Decl(x, t.Css, Value(t, v, theme));
        }
        foreach (var unknown in theme.Tokens.Where(p => contract[p.Key] is null))
            throw new InvalidOperationException($"{theme.Id}: '{unknown.Key}' is not in the contract. Add it there, or move it under chrome.");

        if (theme.Chrome.Count > 0)
        {
            x.AppendLine().AppendLine("  /* chrome: this theme's own decoration colours */");
            foreach (var (k, v) in theme.Chrome) Decl(x, $"{theme.ChromePrefix}-{k}", Refs(v, theme));
        }
        x.AppendLine("}");
        return x.ToString();
    }

    /// <summary>An <c>@import</c> of the base block and every theme, in catalogue order.</summary>
    public static string WriteIndex(TokenSet set)
    {
        var x = new StringBuilder();
        x.Append("/* ").AppendFormat(Banner, "themes.json").AppendLine(" */");
        x.AppendLine("@import \"./base.css\";");
        foreach (var t in set.Themes) x.Append("@import \"./").Append(t.Id).AppendLine(".css\";");
        return x.ToString();
    }

    private static void Group(StringBuilder x, TokenDefinition t, ref string? group)
    {
        var g = t.Name[..t.Name.IndexOf('.')];
        if (g == group) return;
        x.AppendLine().Append("  /* ").Append(g).AppendLine(" */");
        group = g;
    }

    private static void Decl(StringBuilder x, string property, string value) =>
        x.Append("  ").Append(($"--{property}:").PadRight(28)).Append(' ').Append(value).AppendLine(";");

    private string Value(TokenDefinition t, string value, ThemeSource? theme)
    {
        if (t.Kind == TokenKind.Dimension && double.TryParse(value, System.Globalization.CultureInfo.InvariantCulture, out _))
            return value + "px";
        return Refs(value, theme);
    }

    /// <summary>Token references as <c>var()</c>: <c>{surface.panel}</c> → <c>var(--surface-panel)</c>.</summary>
    private string Refs(string value, ThemeSource? theme) =>
        ThemeSource.Reference().Replace(value, m =>
        {
            var name = m.Groups[1].Value;
            if (name.StartsWith("chrome.", StringComparison.Ordinal) && theme is not null)
                return $"var(--{theme.ChromePrefix}-{name[7..]})";
            return contract[name] is { } t ? $"var(--{t.Css})" : throw new InvalidOperationException($"Unknown reference {m.Value}.");
        });
}
